# Builds docs/CODEMAP.md: which build layer wraps or defines what, so Claude can find code without reading files.
# Run after every build:  python tools/codemap.py
import os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
idx = open(os.path.join(ROOT, "index.html"), encoding="utf8").read()
order = re.findall(r'<script src="((?:v\d+|phys/[\w-]+)\.js)"', idx)  # vNN layers and the phys/ module files, in load order

WRAP = re.compile(r'(?<![\w.$])([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?function\b')
DEF = re.compile(r'(?:^|[;\n}])\s*(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(')
CONST = re.compile(r'(?:^|[;\n}])\s*(?:const|let|var)\s+([A-Z][A-Z0-9_]{2,}\d*)\s*=')

def scan(text):
    wraps = sorted(set(WRAP.findall(text)) - {"onclick", "onerror", "onload", "oninput", "onchange", "onmessage", "onpointerdown", "onpointerup", "onpointermove", "onkeydown", "fn", "f", "cb", "h"})
    defs = sorted(set(DEF.findall(text)))
    consts = sorted(set(CONST.findall(text)))
    m = re.match(r'\s*/\*\s*(.*?)\*/', text, re.S)
    head = re.sub(r'\s+', ' ', m.group(1)).strip()[:220] if m else ""
    return head, wraps, defs, consts

rows, who = [], {}
# index.html layers
parts = re.split(r'/\*\s*=====\s*((?:v|b)\d+[^=]*?)=====\s*\*/', idx)
for i in range(1, len(parts), 2):
    name = parts[i].strip()[:60]
    _, wraps, defs, consts = scan(parts[i + 1])
    rows.append((f"index.html · {name}", "", wraps, defs, consts))
for f in order:
    head, wraps, defs, consts = scan(open(os.path.join(ROOT, f), encoding="utf8").read())
    rows.append((f, head, wraps, defs, consts))
for name, _, wraps, defs, _c in rows:
    tag = name.split(" ")[0] if name.startswith(("v", "phys/")) else "ix:" + name.replace("index.html · ", "").split(" ")[0].split(":")[0]
    for w in wraps: who.setdefault(w, []).append(tag)

out = ["# Code map (generated by tools/codemap.py — do not edit by hand)", "",
       "Use this to find where something lives before opening files. `index.html` is ~1.6 MB: grep it, never read it whole.",
       "Load order: index.html layers (v4…b31), then " + " → ".join(order) + ".", "",
       "## Most-wrapped functions (last listed wins; every wrapper calls the one before)", ""]
for fn, ls in sorted(who.items(), key=lambda x: -len(x[1])):
    if len(ls) >= 3: out.append(f"- `{fn}` ×{len(ls)}: " + ", ".join(ls))
out += ["", "## Per layer", "", "Legend: **wraps/reassigns** · *defines* · CONSTANTS", ""]
for name, head, wraps, defs, consts in rows:
    line = f"- **{name}**"
    if head: line += f" — {head}"
    out.append(line)
    bits = []
    if wraps: bits.append("**" + ", ".join(wraps[:40]) + ("…" if len(wraps) > 40 else "") + "**")
    if defs: bits.append("*" + ", ".join(defs[:40]) + ("…" if len(defs) > 40 else "") + "*")
    if consts: bits.append(", ".join(consts[:25]) + ("…" if len(consts) > 25 else ""))
    if bits: out.append("  " + " · ".join(bits))
open(os.path.join(ROOT, "docs", "CODEMAP.md"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("docs/CODEMAP.md:", len(rows), "layers,", sum(1 for v in who.values() if len(v) >= 3), "functions wrapped 3+ times")
